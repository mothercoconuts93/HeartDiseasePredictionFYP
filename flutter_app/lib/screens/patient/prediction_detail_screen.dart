import 'package:flutter/material.dart';

import '../../models/prediction_model.dart';
import '../../themes/app_theme.dart';
import '../../widgets/risk_badge.dart';
import '../../widgets/risk_gradient_bar.dart';

class PredictionDetailScreen extends StatelessWidget {
  final PredictionModel prediction;

  const PredictionDetailScreen({super.key, required this.prediction});

  Color get _riskColor {
    if (prediction.riskLevel.contains('High')) return AppTheme.danger;
    if (prediction.riskLevel.contains('Moderate')) return AppTheme.warning;
    return AppTheme.success;
  }

  String _formatDate(DateTime date) {
    final local = date.toLocal();
    final hour = local.hour % 12 == 0 ? 12 : local.hour % 12;
    final minute = local.minute.toString().padLeft(2, '0');
    final period = local.hour >= 12 ? 'PM' : 'AM';
    return '${local.day}/${local.month}/${local.year} • $hour:$minute $period';
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('CARDIOGUARD')),
      body: ListView(
        padding: const EdgeInsets.all(20),
        children: [
          Text(
            'Assessment Details',
            style: Theme.of(context).textTheme.headlineSmall,
          ),
          const SizedBox(height: 6),
          Text(_formatDate(prediction.createdAt)),
          const SizedBox(height: 20),
          Card(
            child: Padding(
              padding: const EdgeInsets.all(20),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Text(
                    'CALCULATED RISK',
                    style: TextStyle(
                      color: AppTheme.textSecondary,
                      fontSize: 11,
                      letterSpacing: 1.1,
                    ),
                  ),
                  const SizedBox(height: 12),
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceBetween,
                    children: [
                      RiskBadge(riskLevel: prediction.riskLevel),
                      Text(
                        '${prediction.probability.toStringAsFixed(2)}%',
                        style: TextStyle(
                          fontFamily: 'monospace',
                          color: _riskColor,
                          fontSize: 24,
                          fontWeight: FontWeight.w800,
                        ),
                      ),
                    ],
                  ),
                  const SizedBox(height: 18),
                  RiskGradientBar(probability: prediction.probability),
                ],
              ),
            ),
          ),
          const SizedBox(height: 16),
          Card(
            child: Padding(
              padding: const EdgeInsets.all(20),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Row(
                    children: [
                      Icon(
                        Icons.medical_services_outlined,
                        color: AppTheme.primary,
                      ),
                      SizedBox(width: 10),
                      Text(
                        'Medical Recommendation',
                        style: TextStyle(fontWeight: FontWeight.w700),
                      ),
                    ],
                  ),
                  const SizedBox(height: 14),
                  Text(prediction.recommendation),
                ],
              ),
            ),
          ),
          const SizedBox(height: 16),
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: AppTheme.lightBlue,
              borderRadius: BorderRadius.circular(12),
            ),
            child: const Text(
              'This result is generated by a statistical model and is not a medical diagnosis. Consult a qualified healthcare professional.',
              style: TextStyle(fontSize: 11, fontStyle: FontStyle.italic),
            ),
          ),
          const SizedBox(height: 18),
          SelectableText(
            'Reference: ${prediction.predictionId}',
            style: const TextStyle(
              fontFamily: 'monospace',
              fontSize: 10,
              color: AppTheme.textSecondary,
            ),
          ),
        ],
      ),
    );
  }
}
